"""Generate frontend panel constants from the measured common definition."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODEL = ROOT / "crates/pocket-library/data/ppc2003-panel.json"
START = "  // BEGIN generated PPC2003 panel\n"
END = "  // END generated PPC2003 panel\n"


def outputs():
    model = json.loads(MODEL.read_text())
    web = ROOT / "frontends/pocket-wasm/web/library-ui.js"
    source = web.read_text()
    block = START + "  const ppc2003 = Object.freeze(" + json.dumps(model, separators=(",", ":")) + ");\n" + END
    if START in source:
        begin = source.index(START)
        end = source.index(END, begin) + len(END)
        source = source[:begin] + block + source[end:]
    else:
        source = source.replace("  const words =", block + "  const words =", 1)
    kotlin = ROOT / "frontends/pocket-android/app/src/main/java/com/pockethle/app/Ppc2003Panel.kt"
    payload = json.dumps(model, separators=(",", ":"))
    generated = ('// Generated by tools/ui/generate-panel.py. Edit the shared JSON.\n'
                 'package com.pockethle.app\n\n'
                 'internal object Ppc2003Panel {\n'
                 f'    private val model = org.json.JSONObject("""{payload}""")\n'
                 '    val buttons = model.getJSONArray("buttons")\n'
                 '    fun button(vk: Int): org.json.JSONObject? = (0 until buttons.length())\n'
                 '        .map { buttons.getJSONObject(it) }.firstOrNull { it.getInt("vk") == vk }\n'
                 '    fun keys() = (0 until buttons.length()).map { buttons.getJSONObject(it).getInt("vk") }\n'
                 '}\n')
    return {web: source, kotlin: generated}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, value in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != value:
                raise SystemExit(f"Stale panel definition: {path.relative_to(ROOT)}")
        else:
            path.write_text(value)
